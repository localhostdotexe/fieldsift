"""Turn the findings into a starting point for an ImHex pattern."""

from .core import Finding

NAMES = {"length": "size", "pointer": "ptr", "checksum": "sum", "digest": "digest",
         "time": "timestamp", "string": "str"}


def _ctype(f):
    if f.width == 1:
        return "u8"
    return "%s u%d" % (f.endian or "le", f.width * 8)


def _decl(f, name):
    if f.kind in ("magic", "const"):
        return "u8 %s[%d];" % (name, f.width)
    if f.kind == "digest":
        return "u8 %s[%d];" % (name, f.width)
    if f.kind == "time" and f.width == 4:
        return "%s %s [[format(\"fmt_time\")]];" % (_ctype(f), name)
    return "%s %s;" % (_ctype(f), name)


def _name(f, seen):
    if f.kind == "magic":
        return "magic"
    base = NAMES.get(f.kind, "fixed")
    if f.kind == "checksum":
        base = f.info["algo"].split("/")[0].split(" ")[0].strip("-~(") or "sum"
    seen[base] = seen.get(base, 0) + 1
    return base if seen[base] == 1 else "%s%d" % (base, seen[base])


def render(res):
    out = ["// generated by fieldsift, meant as a starting point, not a finished pattern",
           "import std.mem;"]
    if any(f.kind == "time" for f in res.fields):
        out += ["import std.time;", "",
                "fn fmt_time(u32 t) {", "    return std::time::format(std::time::to_utc(t));", "};"]
    out.append("")
    seen = {}
    head = [f for f in res.fields if f.frame == "start" and f.kind != "zero"]
    tail = [f for f in res.fields if f.frame == "end" and f.kind != "zero"]
    ch = res.chunks
    stop = ch["start"] if ch else None

    body = []
    cur = 0
    for f in head:
        if stop is not None and f.off >= stop:
            break
        if f.off < cur:
            continue
        if stop is not None and f.off + f.width > stop:
            if f.kind not in ("magic", "const"):
                break
            # a constant run that spills into the first chunk
            f = Finding(f.kind, f.frame, f.off, stop - f.off)
        if f.off > cur:
            body.append("    u8 unk_%02x[%d];" % (cur, f.off - cur))
        name = _name(f, seen)
        line = "    " + _decl(f, name)
        if f.note:
            line += "  // " + f.note
        body.append(line)
        cur = f.off + f.width
        if f.kind == "string":
            body.append("    char %s_text[%s];" % (name, name))
            body.append("    // layout past this point moves with the string")
            break
    if stop is not None and cur < stop:
        body.append("    u8 unk_%02x[%d];" % (cur, stop - cur))
    if body:
        out += ["struct Header {"] + body + ["};", "", "Header header @ 0x00;", ""]

    if ch:
        lay = ch["layout"]
        ln = "u8 length;" if lay.len == 1 else "%s u%d length;" % (lay.endian, lay.len * 8)
        tag = "char tag[%d];" % lay.tag if lay.tag else None
        rows = [x for x in ((tag, ln) if lay.order != "LT" else (ln, tag)) if x]
        if lay.counts == "total":
            rows.append("u8 data[length - %d];" % (lay.tag + lay.len + lay.trail))
        else:
            rows.append("u8 data[length];")
        if lay.trail:
            en = ch["trailer"][1] if ch["trailer"] else "le"
            what = ch["trailer"][0] if ch["trailer"] else "unknown"
            rows.append("%s u32 trailer;  // %s" % (en, what))
        if lay.align > 1:
            rows.append("padding[(%d - $ %% %d) %% %d];" % (lay.align, lay.align, lay.align))
        out += ["struct Chunk {"] + ["    " + r for r in rows] + ["};", ""]
        out.append("Chunk chunks[while(!std::mem::eof())] @ 0x%02x;" % ch["start"])
        out.append("")

    for f in tail:
        if ch and f.kind == "const":
            continue  # belongs to the last chunk
        name = _name(f, seen)
        line = "%s @ std::mem::size() - %d;" % (_decl(f, name).rstrip(";"), -f.off)
        if f.note:
            line += "  // " + f.note
        out.append(line)
    return "\n".join(out).rstrip() + "\n"
